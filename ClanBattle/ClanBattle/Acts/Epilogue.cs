namespace ClanBattle;

// Фінальна сцена залежить від результату бою й від кількості виконаних актів
public static class Epilogue
{
    public static string For(BattleOutcome outcome, int stars) => outcome switch
    {
        BattleOutcome.PlayerWon when stars >= 3 =>
            "Інарі відчиняє двері святилища й схиляє перед вами дев'ять хвостів. Про цю ніч складуть легенди: такого клану Сто Духів іще не бачили.",
        BattleOutcome.PlayerWon =>
            "Інарі відчиняє двері святилища. Перемога дісталась нелегко, і Сто Духів іще довго пам'ятатимуть, чого вона коштувала.",
        BattleOutcome.EnemyWon =>
            "Двері святилища зачиняються. Туман ховає ваші прапори до наступного століття, але Дзеркало Спогадів пам'ятає все.",
        _ =>
            "Світанок розвіює духів, і святилище лишається нічийним до наступної Ночі Ста Духів."
    };
}
